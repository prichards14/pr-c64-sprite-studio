/**
 * Commodore 64 BASIC V2 Exporter and Parser
 * Generates ready-to-run .BAS program starting at line 100 and DATA statements at line 1000.
 * Also parses .BAS code back into sprite data and register settings.
 */

class BasicGenerator {
  /**
   * Generate Commodore 64 BASIC V2 listing
   * @param {C64Sprite} sprite 
   * @param {Object} options 
   */
  static generate(sprite, options = {}) {
    const isMulticolor = sprite.mode === 'lores';
    const xExpand = sprite.expandX ? 1 : 0;
    const yExpand = sprite.expandY ? 1 : 0;
    const spriteNum = options.spriteNumber !== undefined ? options.spriteNumber : 0;
    const spritePointerAddr = 2040 + spriteNum; // 2040 = 1024 + 1016 (Sprite 0 pointer)
    const spriteEnableBit = 1 << spriteNum;
    const format = options.dataFormat || 'rows'; // 'rows' (3 bytes/line) or 'compact' (8 bytes/line)
    const codeCase = options.codeCase || 'upper'; // 'upper' or 'lower'

    const lines = [];

    // Header & Setup starting at Line 100
    lines.push('100 REM ========================================');
    lines.push(`105 REM C64 SPRITE ${spriteNum} DISPLAY ROUTINE`);
    lines.push('110 REM GENERATED BY C64 SPRITE STUDIO');
    lines.push('115 REM ========================================');
    lines.push('120 V=53248:REM VIC-II BASE REGISTER ($D000)');
    lines.push('130 POKE 53280,0:REM BORDER COLOR -> BLACK');
    lines.push(`140 POKE 53281,${sprite.colors.bg}:REM BACKGROUND COLOR`);
    lines.push('150 REM READ 63 BYTES OF SPRITE DATA INTO CASSETTE BUFFER ($0340=832)');
    lines.push('160 FOR I=0 TO 62:READ D:POKE 832+I,D:NEXT I');
    lines.push(`170 POKE ${spritePointerAddr},13:REM SET SPRITE ${spriteNum} POINTER -> BLOCK 13 (832/64)`);
    lines.push(`180 POKE V+${spriteNum * 2},160:POKE V+${spriteNum * 2 + 1},130:REM SPRITE ${spriteNum} X,Y POS`);
    lines.push(`190 POKE V+${39 + spriteNum},${sprite.colors.sprite}:REM SPRITE ${spriteNum} COLOR`);
    lines.push(`200 POKE V+28,${isMulticolor ? spriteEnableBit : 0}:REM MULTICOLOR (0=HIRES, 1=LORES)`);

    if (isMulticolor) {
      lines.push(`210 POKE V+37,${sprite.colors.mc1}:REM MULTICOLOR 1 ($D025)`);
      lines.push(`220 POKE V+38,${sprite.colors.mc2}:REM MULTICOLOR 2 ($D026)`);
    } else {
      lines.push('210 REM HIRES MODE (MONOCHROME)');
    }

    lines.push(`230 POKE V+29,${xExpand ? spriteEnableBit : 0}:REM X EXPAND (DOUBLE WIDTH)`);
    lines.push(`240 POKE V+23,${yExpand ? spriteEnableBit : 0}:REM Y EXPAND (DOUBLE HEIGHT)`);
    lines.push(`250 POKE V+21,PEEK(V+21) OR ${spriteEnableBit}:REM ENABLE SPRITE ${spriteNum}`);
    lines.push('260 PRINT CHR$(147);:REM CLEAR SCREEN');
    lines.push(`270 PRINT "SPRITE ${spriteNum} ACTIVE!"`);
    lines.push('280 REM SPRITE DISPLAY LOOP:');
    lines.push('290 GOTO 290');

    // Sprite DATA statements starting at Line 1000
    const bytes = sprite.bytes;
    if (format === 'rows') {
      // 21 lines of 3 bytes each (1 line per sprite row)
      let lineNum = 1000;
      for (let row = 0; row < 21; row++) {
        const b0 = bytes[row * 3];
        const b1 = bytes[row * 3 + 1];
        const b2 = bytes[row * 3 + 2];
        lines.push(`${lineNum} DATA ${b0},${b1},${b2}`);
        lineNum += 10;
      }
    } else {
      // Compact format (8 bytes per line)
      let lineNum = 1000;
      for (let i = 0; i < 63; i += 8) {
        const slice = [];
        for (let j = 0; j < 8 && (i + j) < 63; j++) {
          slice.push(bytes[i + j]);
        }
        lines.push(`${lineNum} DATA ${slice.join(',')}`);
        lineNum += 10;
      }
    }

    const result = lines.join('\n');
    return codeCase === 'lower' ? result.toLowerCase() : result.toUpperCase();
  }

  /**
   * Parse a Commodore BASIC listing to extract sprite data and configuration
   * @param {string} text 
   * @returns {Object} { bytes, mode, colors, expandX, expandY }
   */
  static parse(text) {
    const rawLines = text.split(/\r?\n/);
    const dataValues = [];

    let detectedMode = null;
    let detectedBg = null;
    let detectedSpriteColor = null;
    let detectedMc1 = null;
    let detectedMc2 = null;
    let detectedExpandX = null;
    let detectedExpandY = null;

    for (const line of rawLines) {
      // Extract DATA statements
      const dataMatch = line.match(/^\s*(\d+)?\s*DATA\s+(.*)$/i);
      if (dataMatch) {
        const items = dataMatch[2].split(',');
        for (const item of items) {
          const trimmed = item.trim();
          if (trimmed.length > 0) {
            let val = parseInt(trimmed, 10);
            if (trimmed.startsWith('$')) {
              val = parseInt(trimmed.substring(1), 16);
            }
            if (!isNaN(val)) {
              dataValues.push(val & 0xFF);
            }
          }
        }
      }

      // Check for POKE statements for settings
      // POKE 53281, <bg>
      const bgMatch = line.match(/POKE\s+53281\s*,\s*(\d+)/i);
      if (bgMatch) detectedBg = parseInt(bgMatch[1], 10);

      // Multicolor register V+28 or 53276
      const mcMatch = line.match(/POKE\s+(?:V\s*\+\s*28|53276)\s*,\s*(\d+)/i);
      if (mcMatch) {
        const v = parseInt(mcMatch[1], 10);
        detectedMode = v > 0 ? 'lores' : 'hires';
      }

      // Sprite Color V+39 or 53287
      const scMatch = line.match(/POKE\s+(?:V\s*\+\s*39|53287)\s*,\s*(\d+)/i);
      if (scMatch) detectedSpriteColor = parseInt(scMatch[1], 10);

      // MC1 V+37 or 53285
      const mc1Match = line.match(/POKE\s+(?:V\s*\+\s*37|53285)\s*,\s*(\d+)/i);
      if (mc1Match) detectedMc1 = parseInt(mc1Match[1], 10);

      // MC2 V+38 or 53286
      const mc2Match = line.match(/POKE\s+(?:V\s*\+\s*38|53286)\s*,\s*(\d+)/i);
      if (mc2Match) detectedMc2 = parseInt(mc2Match[1], 10);

      // X Expand V+29 or 53277
      const expXMatch = line.match(/POKE\s+(?:V\s*\+\s*29|53277)\s*,\s*(\d+)/i);
      if (expXMatch) detectedExpandX = parseInt(expXMatch[1], 10) > 0;

      // Y Expand V+23 or 53271
      const expYMatch = line.match(/POKE\s+(?:V\s*\+\s*23|53271)\s*,\s*(\d+)/i);
      if (expYMatch) detectedExpandY = parseInt(expYMatch[1], 10) > 0;
    }

    if (dataValues.length < 63) {
      throw new Error(`Found only ${dataValues.length} DATA values in file. Commodore 64 sprites require at least 63 bytes.`);
    }

    const spriteBytes = new Uint8Array(63);
    for (let i = 0; i < 63; i++) {
      spriteBytes[i] = dataValues[i];
    }

    return {
      bytes: spriteBytes,
      mode: detectedMode,
      colors: {
        bg: detectedBg,
        sprite: detectedSpriteColor,
        mc1: detectedMc1,
        mc2: detectedMc2
      },
      expandX: detectedExpandX,
      expandY: detectedExpandY
    };
  }
}

// Export for Node/ESM/Browser
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { BasicGenerator };
}

